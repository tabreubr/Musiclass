-- V1: schema inicial do Musiclass.
-- Reproduz o schema que o Hibernate gerava com ddl-auto=update a partir das
-- entidades (nomes em snake_case, ids IDENTITY). A partir daqui, toda mudança
-- de banco entra como uma nova migration (V2, V3, ...), nunca editando esta.

CREATE TABLE instructor (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255) NOT NULL,
    email    VARCHAR(255),
    password VARCHAR(255),
    role     VARCHAR(255) NOT NULL,
    CONSTRAINT ck_instructor_role CHECK (role IN ('INSTRUCTOR', 'STUDENT', 'ADMIN'))
);

CREATE TABLE instrument (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_instrument_name UNIQUE (name)
);

CREATE TABLE method (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE method_instrument (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_id     BIGINT,
    instrument_id BIGINT,
    CONSTRAINT fk_method_instrument_method     FOREIGN KEY (method_id)     REFERENCES method (id),
    CONSTRAINT fk_method_instrument_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id)
);

CREATE TABLE student (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    instrument_id BIGINT,
    instructor_id BIGINT,
    email         VARCHAR(255),
    password      VARCHAR(255),
    CONSTRAINT uk_student_email UNIQUE (email),
    CONSTRAINT fk_student_instrument FOREIGN KEY (instrument_id) REFERENCES instrument (id),
    CONSTRAINT fk_student_instructor FOREIGN KEY (instructor_id) REFERENCES instructor (id)
);

CREATE TABLE classes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date          TIMESTAMP(6) NOT NULL,
    observations  VARCHAR(255),
    passed        BOOLEAN,
    student_id    BIGINT,
    instructor_id BIGINT,
    deleted       BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_classes_student    FOREIGN KEY (student_id)    REFERENCES student (id),
    CONSTRAINT fk_classes_instructor FOREIGN KEY (instructor_id) REFERENCES instructor (id)
);

CREATE TABLE lesson (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classes_id     BIGINT,
    method_name_id BIGINT,
    page           INTEGER,
    lesson_number  INTEGER,
    completed      BOOLEAN,
    CONSTRAINT fk_lesson_classes FOREIGN KEY (classes_id)     REFERENCES classes (id),
    CONSTRAINT fk_lesson_method  FOREIGN KEY (method_name_id) REFERENCES method (id)
);

CREATE TABLE development_goal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    deadline    DATE,
    student_id  BIGINT,
    completed   BOOLEAN,
    CONSTRAINT fk_development_goal_student FOREIGN KEY (student_id) REFERENCES student (id)
);

CREATE TABLE progress_goal (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deadline             DATE,
    target_lesson_number INTEGER NOT NULL,
    student_id           BIGINT,
    method_id            BIGINT,
    completed            BOOLEAN,
    CONSTRAINT fk_progress_goal_student FOREIGN KEY (student_id) REFERENCES student (id),
    CONSTRAINT fk_progress_goal_method  FOREIGN KEY (method_id)  REFERENCES method (id)
);

CREATE TABLE invite_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(255) NOT NULL,
    student_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    used       BOOLEAN NOT NULL,
    CONSTRAINT uk_invite_token_token UNIQUE (token),
    CONSTRAINT fk_invite_token_student FOREIGN KEY (student_id) REFERENCES student (id)
);
